// Copies the few simple-icons logos the skills table uses into
// src/data/brandIcons.js, so the app never imports the 5 MB `simple-icons`
// package (Vite's dev pre-bundle shipped all ~3,000 icons on every load).
// Run after adding a skill:  node scripts/gen-brand-icons.mjs
import { writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const NAMES = [
  "siHtml5", "siCss", "siJavascript", "siReact", "siVuedotjs", "siTailwindcss", "siBootstrap",
  "siPhp", "siLaravel", "siPython", "siFastapi",
  "siMysql", "siPostgresql", "siMongodb", "siGit", "siPostman", "siDocker", "siJira",
  "siFigma",
];

const lines = NAMES.map((name) => {
  const icon = icons[name];
  if (!icon) throw new Error(`simple-icons has no ${name}`);
  return `export const ${name} = ${JSON.stringify({ title: icon.title, hex: icon.hex, path: icon.path })};`;
});

writeFileSync(
  new URL("../src/data/brandIcons.js", import.meta.url),
  `// Generated by scripts/gen-brand-icons.mjs from simple-icons (CC0). Do not edit.\n${lines.join("\n")}\n`
);
console.log(`Wrote ${NAMES.length} icons.`);
